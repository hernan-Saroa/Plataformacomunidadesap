/**
 * Helpers
 */
export function getEventosPorCategoria(categoria: string) {
  return EVENTOS_2026_1.filter(e => e.categoria === categoria);
}

export function getEventosPorUsuario(tipoUsuario: string) {
  return EVENTOS_2026_1.filter(e => e.aplicaA.includes(tipoUsuario as any));
}

export function getEventosPorFecha(fecha: string) {
  return EVENTOS_2026_1.filter(e => {
    if (e.fechaFin) {
      return fecha >= e.fechaInicio && fecha <= e.fechaFin;
    }
    return e.fechaInicio === fecha;
  });
}
