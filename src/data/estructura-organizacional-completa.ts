/**
 * Función helper para obtener estructura por nivel
 */
export const getUnidadesPorNivel = (nivel: 'nacional' | 'territorial' | 'sede'): UnidadOrganizacional[] => {
  return ESTRUCTURA_ORGANIZACIONAL_ESAP.filter(u => u.nivel === nivel);
};

/**
 * Función helper para obtener hijos de una unidad
 */
export const getHijosUnidad = (padreId: string): UnidadOrganizacional[] => {
  return ESTRUCTURA_ORGANIZACIONAL_ESAP.filter(u => u.padreId === padreId);
};