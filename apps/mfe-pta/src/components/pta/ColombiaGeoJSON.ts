// ═══════════════════════════════════════════════════════════════
// Projection helpers: WGS84 → SVG viewBox coordinates
// ViewBox: 0 0 600 760
// Colombia: lat -4.3 to 12.6, lng -81.8 (San Andrés) to -66.8
// Main land: lng -79 to -66.8
// ═══════════════════════════════════════════════════════════════

const LNG_MIN = -79.2;
const LNG_MAX = -66.5;
const LAT_MIN = -4.5;
const LAT_MAX = 12.8;
const VB_W = 600;
const VB_H = 760;
const PAD = 15;

export function projectLng(lng: number): number {
  return PAD + ((lng - LNG_MIN) / (LNG_MAX - LNG_MIN)) * (VB_W - 2 * PAD);
}

export function projectLat(lat: number): number {
  return PAD + ((LAT_MAX - lat) / (LAT_MAX - LAT_MIN)) * (VB_H - 2 * PAD);
}

/** Convert [lng,lat] coordinates to SVG path d string */
export function coordsToPath(coords: [number, number][][]): string {
  return coords.map(ring => {
    const points = ring.map(([lng, lat]) => `${projectLng(lng).toFixed(1)},${projectLat(lat).toFixed(1)}`);
    return `M${points.join('L')}Z`;
  }).join(' ');
}

/** Project a single lat/lng to SVG coordinates */
export function projectPoint(lat: number, lng: number): { x: number; y: number } {
  return { x: projectLng(lng), y: projectLat(lat) };
}

/** Get center of a department for label placement */
export function getDeptCenter(dept: DeptFeature): { x: number; y: number } {
  const ring = dept.coords[0];
  let sumLng = 0, sumLat = 0;
  ring.forEach(([lng, lat]) => { sumLng += lng; sumLat += lat; });
  const n = ring.length;
  return projectPoint(sumLat / n, sumLng / n);
}